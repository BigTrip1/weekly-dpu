// Second pass over the Failed To values that first arrived unmapped. Each group follows the
// naming pattern of a value that was already mapped. Change any of them on the Departments page.
export function extendedMappings(): DeptMapping[] {
  const make = (label: string, department: string | null, defectTypeContains = ""): DeptMapping => ({
    failedToKey: label.toLowerCase(),
    failedToLabel: label,
    department,
    hidden: department === null,
    defectTypeContains,
  });

  const production = [
    // Numbered zones continue Zone 3 to Zone 6.
    "Zone 1",
    "Zone 2",
    "Zone 7",
    "Zone 7 Rectification",
    // Sub-assembly stations continue Boom Sub Assembly.
    "Engine Sub Assembly",
    "Axle Sub Assembly",
    "Cooling Pack Sub Assembly",
    "Leg Sub Assembly",
    "Ram Sub Assembly",
    "Scr Sub Assembly",
    "Fuel Tank Sub Assembly",
    "Power Systems",
    "Transmissions",
    "Attachments",
    // Line, test, rectification and finishing stages of the build.
    "Assembly",
    "Assembly Track",
    "Static Build",
    "Off Track",
    "Cycle Test",
    "Rectification",
    "Heavy Rectification",
    "Standard Work",
    "Customer Focus Centre",
    "Finishing Ldl",
  ];
  const manufacturing = [
    // Boom and chassis fabrication continues Chassis, Machining and Fabrication Manufacturing.
    "Manufacturing",
    "Boom Manufacturing",
    "Inner Boom Manufacturing",
    "Outer Boom Manufacturing",
    "India Fab",
    "Hbu",
    "Maintenance",
  ];

  return [
    ...production.map((label) => make(label, "Production")),
    ...manufacturing.map((label) => make(label, "Manufacturing Facilities")),
    make("Boom Kitting", "Parts / POF"),
    // A knock-on fault is a symptom of another fault, so it stays off the panels.
    make("Consequential Fault", null),
  ];
}

